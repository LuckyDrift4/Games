"""Export the clips for Roblox: a Luau data module for the in-game animator (no uploads needed) and a JSON file the
Lune place builder turns into KeyframeSequences (for the Animation Editor / uploading).

Clips are baked at rig.FPS from the posing keys in clips.py, so Roblox plays exactly the frames the Blender preview
shows. Each stroke also exports where the racket meets the ball (relative to the HumanoidRootPart), which the server
uses for its hit checks and the bot for where to stand.

    python3 game/anim/export.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import r6  # noqa: E402
import rig  # noqa: E402
from clips import CLIPS, ORDER  # noqa: E402

GAME = os.path.dirname(HERE)
LUA = os.path.join(GAME, 'src', 'ReplicatedStorage', 'Tennis', 'AnimData.lua')
JSON = os.path.join(GAME, 'build', 'anims.json')
HEAD_CENTER = 2.01      # racket string-bed centre, studs above the hand


def comps(M):
    """CFrame.new(x, y, z, R00, R01, R02, R10, R11, R12, R20, R21, R22)"""
    return [round(M[0][3], 4), round(M[1][3], 4), round(M[2][3], 4)] + [round(M[i][j], 5) for i in range(3) for j in range(3)]


def quat_comps(M):
    """CFrame.new(x, y, z, qX, qY, qZ, qW)"""
    q = r6.to_quat(M)
    if q[3] < 0:
        q = tuple(-c for c in q)
    return [round(M[0][3], 4), round(M[1][3], 4), round(M[2][3], 4)] + [round(c, 5) for c in q]


def num(x):
    s = ('%.5f' % x).rstrip('0').rstrip('.')
    return '0' if s in ('', '-0') else s


def vec(v):
    return '{ %s }' % ', '.join(num(round(c, 3)) for c in v)


def main():
    data = {}
    for name in ORDER:
        c = CLIPS[name]
        frames = rig.bake(c)
        info = {'length': c['length'], 'loop': c['loop'], 'priority': c['priority'], 'contact': c.get('contact'),
                'toss': c.get('toss'), 'frames': [(t, mats) for t, mats, _ in frames]}
        if c.get('contact') is not None:
            i = min(range(len(frames)), key=lambda j: abs(frames[j][0] - c['contact']))
            info['contact_point'] = rig.racket_point(frames[i][1], HEAD_CENTER)
        if c.get('toss') is not None:
            i = min(range(len(frames)), key=lambda j: abs(frames[j][0] - c['toss']))
            W = rig.world(frames[i][1])
            info['toss_point'] = rig.pos_of(r6.mul(W['Left Arm'], r6.mat(p=(0, -1.25, -0.1))))
        data[name] = info
    os.makedirs(os.path.dirname(JSON), exist_ok=True)
    joints = {j: {'part0': r6.JOINTS[j][0], 'part1': r6.JOINTS[j][1], 'motor': r6.JOINTS[j][4],
                  'c0': comps(r6.JOINTS[j][2]), 'c1': comps(r6.JOINTS[j][3])} for j in r6.ORDER}
    jclips = {}
    for name, info in data.items():
        jclips[name] = {'length': info['length'], 'loop': info['loop'], 'priority': info['priority'],
                        'keys': [{'t': round(t, 4), 'e': 'linear', 'p': {j: comps(m[j]) for j in r6.ORDER}}
                                 for t, m in info['frames']]}
    json.dump({'order': r6.ORDER, 'joints': joints, 'clips': jclips}, open(JSON, 'w'))
    L = ['-- GENERATED by game/anim/export.py from game/anim/clips.py (posed with IK and previewed in Blender, baked at',
         '-- %d fps). Do not edit by hand. Each key: T = time, P = Motor6D.Transform per joint as CFrame.new(x, y, z,' % rig.FPS,
         '-- qX, qY, qZ, qW). ContactPoint = where the racket meets the ball, relative to the HumanoidRootPart.',
         'return {',
         '\tFps = %d,' % rig.FPS,
         '\tJoints = { %s },' % ', '.join('"%s"' % j for j in r6.ORDER),
         '\tMotors = { %s },' % ', '.join('%s = "%s"' % (j, r6.JOINTS[j][4]) for j in r6.ORDER),
         '\tClips = {']
    for name in ORDER:
        c = data[name]
        L.append('\t\t%s = {' % name)
        extra = ''
        if c['contact'] is not None:
            extra += ' Contact = %s, ContactPoint = %s,' % (num(c['contact']), vec(c['contact_point']))
        if c['toss'] is not None:
            extra += ' Toss = %s, TossPoint = %s,' % (num(c['toss']), vec(c['toss_point']))
        L.append('\t\t\tLength = %s, Loop = %s, Priority = "%s",%s' % (
            num(c['length']), 'true' if c['loop'] else 'false', c['priority'], extra))
        L.append('\t\t\tKeys = {')
        for t, m in c['frames']:
            poses = ', '.join('{%s}' % ','.join(num(v) for v in quat_comps(m[j])) for j in r6.ORDER)
            L.append('\t\t\t\t{ T = %s, P = { %s } },' % (num(round(t, 4)), poses))
        L.append('\t\t\t},')
        L.append('\t\t},')
    L += ['\t},', '}', '']
    open(LUA, 'w').write('\n'.join(L))
    print('EXPORT_OK', len(ORDER), 'clips ->', LUA, '(%d KB)' % (os.path.getsize(LUA) // 1024), JSON)
    for name in ORDER:
        if 'contact_point' in data[name]:
            print('  %-15s contact %s' % (name, [round(v, 2) for v in data[name]['contact_point']]))


main()
