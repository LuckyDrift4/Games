"""Export the clips for Roblox: a Luau data module for the in-game animator (no uploads needed) and a JSON file the
Lune place builder turns into KeyframeSequences (for the Animation Editor / uploading).

    python3 game/anim/export.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import r6  # noqa: E402
from clips import CLIPS, ORDER  # noqa: E402

GAME = os.path.dirname(HERE)
LUA = os.path.join(GAME, 'src', 'ReplicatedStorage', 'Tennis', 'AnimData.lua')
JSON = os.path.join(GAME, 'build', 'anims.json')


def comps(M):
    """CFrame.new(x, y, z, R00, R01, R02, R10, R11, R12, R20, R21, R22)"""
    return [round(M[0][3], 4), round(M[1][3], 4), round(M[2][3], 4)] + [round(M[i][j], 5) for i in range(3) for j in range(3)]


def num(x):
    s = ('%.5f' % x).rstrip('0').rstrip('.')
    return '0' if s in ('', '-0') else s


def main():
    data = {}
    for name in ORDER:
        c = CLIPS[name]
        keys = [{'t': t, 'e': e, 'p': {j: comps(M[j]) for j in r6.ORDER}} for (t, e, M) in r6.resolved_keys(name)]
        data[name] = {'length': c['length'], 'loop': c['loop'], 'priority': c['priority'], 'contact': c.get('contact'),
                      'toss': c.get('toss'), 'keys': keys}
    os.makedirs(os.path.dirname(JSON), exist_ok=True)
    joints = {j: {'part0': r6.JOINTS[j][0], 'part1': r6.JOINTS[j][1], 'motor': r6.JOINTS[j][4],
                  'c0': comps(r6.JOINTS[j][2]), 'c1': comps(r6.JOINTS[j][3])} for j in r6.ORDER}
    json.dump({'order': r6.ORDER, 'joints': joints, 'clips': data}, open(JSON, 'w'), indent=1)
    L = ['-- GENERATED by game/anim/export.py from game/anim/clips.py (made and previewed in Blender). Do not edit by hand.',
         '-- Each key: T = time, E = easing to the next key, P = Motor6D.Transform per joint as CFrame components.',
         'return {',
         '\tJoints = { %s },' % ', '.join('"%s"' % j for j in r6.ORDER),
         '\tMotors = { %s },' % ', '.join('%s = "%s"' % (j, r6.JOINTS[j][4]) for j in r6.ORDER),
         '\tClips = {']
    for name in ORDER:
        c = data[name]
        L.append('\t\t%s = {' % name)
        L.append('\t\t\tLength = %s, Loop = %s, Priority = "%s",%s%s' % (
            num(c['length']), 'true' if c['loop'] else 'false', c['priority'],
            (' Contact = %s,' % num(c['contact'])) if c['contact'] is not None else '',
            (' Toss = %s,' % num(c['toss'])) if c['toss'] is not None else ''))
        L.append('\t\t\tKeys = {')
        for kf in c['keys']:
            poses = ', '.join('{%s}' % ', '.join(num(v) for v in kf['p'][j]) for j in r6.ORDER)
            L.append('\t\t\t\t{ T = %s, E = "%s", P = { %s } },' % (num(kf['t']), kf['e'], poses))
        L.append('\t\t\t},')
        L.append('\t\t},')
    L += ['\t},', '}', '']
    open(LUA, 'w').write('\n'.join(L))
    print('EXPORT_OK', len(ORDER), 'clips ->', LUA, JSON)


main()
