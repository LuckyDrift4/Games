"""Prepare the Blender stadium's .glb files for Roblox Studio's importer and the installer.

1. Studio names an imported model after the glTF *scene*, which the exporter calls "Scene" in every file, so each
   file's scene is renamed to the file name (Stand_w20_0.glb -> model "Stand_w20_0").
2. Writes game/src/ServerStorage/TennisStadiumOffsets.lua: for every prop, the centre and size of its main mesh
   relative to the file origin (glTF frame). Studio puts a MeshPart at the centre of its mesh, so the installer can
   put each model's pivot back on the file origin, whatever pivot / scale options were used when importing.

    python3 game/tools/stadium_glb_fix.py
"""
import glob
import json
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
KIT = os.path.join(ROOT, 'out', 'tennis_stadium_blender', 'roblox')
LUA = os.path.join(ROOT, 'game', 'src', 'ServerStorage', 'TennisStadiumOffsets.lua')


def read_glb(path):
    b = open(path, 'rb').read()
    magic, ver, total = struct.unpack('<4sII', b[:12])
    assert magic == b'glTF', path
    chunks, off = [], 12
    while off < len(b):
        L, kind = struct.unpack('<I4s', b[off:off + 8])
        chunks.append([kind, b[off + 8:off + 8 + L]])
        off += 8 + L
    return ver, chunks


def write_glb(path, ver, chunks):
    body = b''
    for kind, data in chunks:
        pad = (4 - len(data) % 4) % 4
        data = data + ((b' ' if kind == b'JSON' else b'\x00') * pad)
        body += struct.pack('<I4s', len(data), kind) + data
    open(path, 'wb').write(struct.pack('<4sII', b'glTF', ver, 12 + len(body)) + body)


def main():
    files = sorted(glob.glob(os.path.join(KIT, 'kit', '*.glb')) + glob.glob(os.path.join(KIT, 'static', '*.glb'))
                   + [os.path.join(KIT, 'AxisProbe.glb')])
    rows = []
    for path in files:
        stem = os.path.splitext(os.path.basename(path))[0]
        ver, chunks = read_glb(path)
        j = json.loads(chunks[0][1])
        for s in j.get('scenes', []):
            s['name'] = stem
        chunks[0][1] = json.dumps(j, separators=(',', ':')).encode()
        write_glb(path, ver, chunks)
        node = next(n for n in j['nodes'] if n.get('name') == stem)
        mesh = j['meshes'][node['mesh']]
        lo, hi = [1e9] * 3, [-1e9] * 3
        for prim in mesh['primitives']:
            acc = j['accessors'][prim['attributes']['POSITION']]
            lo = [min(a, b) for a, b in zip(lo, acc['min'])]
            hi = [max(a, b) for a, b in zip(hi, acc['max'])]
        t = node.get('translation', [0, 0, 0])
        c = [(a + b) / 2 + d for a, b, d in zip(lo, hi, t)]
        size = [b - a for a, b in zip(lo, hi)]
        rows.append((stem, c, size))
    L = ['-- GENERATED by game/tools/stadium_glb_fix.py. For each stadium model: the centre and size of its main mesh',
         '-- relative to its file origin, in the .glb frame. TennisStadiumInstall uses it to put every imported model\'s',
         '-- pivot back on the file origin (and to undo a wrong import scale).',
         'return {']
    for stem, c, s in rows:
        L.append('\t["%s"] = { c = Vector3.new(%.4f, %.4f, %.4f), size = Vector3.new(%.4f, %.4f, %.4f) },' % (stem, *c, *s))
    L += ['}', '']
    open(LUA, 'w').write('\n'.join(L))
    print('GLB_FIX_OK', len(rows), 'files ->', LUA)


main()
